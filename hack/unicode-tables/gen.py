"""Writes src/internal/findings/unicode_tables.go from Unicode's data files.

Run it with the directory that holds DerivedAge.txt,
DerivedGeneralCategory.txt, DerivedCoreProperties.txt and
emoji-variation-sequences.txt of one Unicode version (from
https://www.unicode.org/Public/<version>/ucd/, the last two under
extracted/ and emoji/):

    python3 -I hack/unicode-tables/gen.py <dir> 17.0.0 > src/internal/findings/unicode_tables.go
"""

import sys

GO_VERSION = "15.0"  # The Unicode version of Go's unicode package.


def load(path, keep=None):
    values = {}
    for line in open(path, encoding="utf-8"):
        line = line.split("#")[0].strip()
        if not line:
            continue
        fields = [f.strip() for f in line.split(";")]
        if keep is not None and fields[1] not in keep:
            continue
        lo, _, hi = fields[0].partition("..")
        for c in range(int(lo, 16), int(hi or lo, 16) + 1):
            values[c] = fields[1]
    return values


def ranges(code_points):
    out = []
    for c in sorted(code_points):
        if out and out[-1][1] == c - 1:
            out[-1][1] = c
        else:
            out.append([c, c])
    return out


def newer(version):
    major, minor = (int(p) for p in version.split("."))
    go_major, go_minor = (int(p) for p in GO_VERSION.split("."))
    return (major, minor) > (go_major, go_minor)


def main(directory, version):
    age = load(f"{directory}/DerivedAge.txt")
    category = load(f"{directory}/DerivedGeneralCategory.txt")
    ignorable = load(f"{directory}/DerivedCoreProperties.txt", {"Default_Ignorable_Code_Point"})
    # Only the visible: letters, marks, numbers, punctuation and symbols.
    # A newer format character or default-ignorable stays a finding.
    assigned = [
        c for c, v in age.items()
        if newer(v) and category[c][0] in "LMNPS" and c not in ignorable
    ]
    bases = set()
    for line in open(f"{directory}/emoji-variation-sequences.txt", encoding="utf-8"):
        line = line.split("#")[0].strip()
        if line:
            bases.add(int(line.split()[0], 16))

    print("// Code generated by hack/unicode-tables/gen.py; DO NOT EDIT.")
    print()
    print("package findings")
    print()
    print(f"// assignedSinceGo are the visible code points Unicode {version} assigned")
    print(f"// after Go's unicode tables ({GO_VERSION}), which those tables call unassigned.")
    print("var assignedSinceGo = []runeRange{")
    for lo, hi in ranges(assigned):
        print(f"\t{{0x{lo:04X}, 0x{hi:04X}}},")
    print("}")
    print()
    print(f"// emojiVariationBases are the code points Unicode {version} gives a text")
    print("// (U+FE0E) and an emoji (U+FE0F) variation sequence.")
    print("var emojiVariationBases = []runeRange{")
    for lo, hi in ranges(bases):
        print(f"\t{{0x{lo:04X}, 0x{hi:04X}}},")
    print("}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
